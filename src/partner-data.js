export function normalizePartnerText(value) {
  return value.normalize("NFD").replace(/\p{M}/gu, "").toLowerCase();
}

export const partners = entries.map((entry) => ({
  ...entry,
  id: normalizePartnerText(entry.name).replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, ""),
  sourceName: entry.sourceName ?? entry.name,
  sourceUrl: entry.profile ? `${partnerSource.url}${entry.profile}/` : partnerSource.url,
}));

export function filterPartners({ query = "", category = "All", range = "All" } = {}) {
  if (category !== "All" && !partnerCategories.includes(category)) {
    throw new RangeError(`Unknown partner category: ${category}`);
  }
  if (!partnerRanges.includes(range)) {
    throw new RangeError(`Unknown partner alphabet range: ${range}`);
  }
  const terms = normalizePartnerText(query).trim().split(/\s+/).filter(Boolean);
  const [first, last] = range.toLowerCase().split("-");
  return partners.filter((partner) => {
    const initial = normalizePartnerText(partner.name)[0];
    const text = normalizePartnerText([
      partner.name, partner.sourceName, partner.category, partner.description,
      partner.website ?? "", ...partner.skills,
    ].join(" "));
    return (category === "All" || partner.category === category) &&
      (range === "All" || (initial >= first && initial <= last)) &&
      terms.every((term) => text.includes(term));
  }).sort((a, b) => a.name.localeCompare(b.name, "en", { sensitivity: "base" }));
}
